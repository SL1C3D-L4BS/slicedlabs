"""docs: render build/docs/*.md from the registries, the ADR log, the dependency lock and the code (WO-031).

Usage (via `just docs`): python3 -I tools/docs/build.py --api doxygen|stub [--root DIR] [--out DIR]

Pages written under build/docs: index.md, overview.md, registry.md, adr.md, dependencies.md,
records.md, api.md. The output is deterministic (no timestamps). Doxygen is run by the just recipe
(ADR-0004: no subprocess in tools); `--api doxygen` says it ran and that build/docs/api/html exists,
`--api stub` writes the stub API page. Stdlib only, no network.
"""

import argparse
import collections
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mdlib  # noqa: E402

OUT_REL = "build/docs"
HEADER_DIRS = ("engine/core/include",)
API_INDEX = "api/html/index.html"
GEN_NOTE = "<!-- Generated by tools/docs/build.py (just docs). Do not edit. -->"


class DocsBuildError(Exception):
    pass


def load(root, rel):
    try:
        with open(os.path.join(root, *rel.split("/")), encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, ValueError) as exc:
        raise DocsBuildError("%s: %s" % (rel, exc))


def esc(text):
    return str(text).replace("|", "\\|")


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(" :---- " for _ in head) + "|"]
    out += ["| " + " | ".join(esc(c) for c in row) + " |" for row in rows]
    return out


def rel_from_out(out_rel, target):
    """Link from a page in out_rel to a repo-relative path."""
    import posixpath

    return posixpath.relpath(target, out_rel)


def page_index(ctx):
    r = ctx["rel"]
    return [
        GEN_NOTE,
        "# Sliced Labs documentation",
        "",
        "Generated by `just docs` from the registries, the ADR log, the dependency lock and the code. Output only",
        "under `build/docs`; `just docs-check` verifies every relative link and cited id.",
        "",
        "- [Overview](overview.md): what exists now and the gate commands (from the repository README).",
        "- [Registries](registry.md): SL-REG-001 documents, SL-REG-002 episodes, and the generated views.",
        "- [Architecture decisions](adr.md): the ADR log (SL-GOV-004).",
        "- [Dependencies and licences](dependencies.md): from `deps/deps.lock.json`.",
        "- [Controlled documents and records](records.md): `docs/gov`, `docs/plan`, `docs/vol`, `docs/episodes`.",
        "- [API reference](api.md): %s."
        % (
            "Doxygen HTML for `engine/core/include`"
            if ctx["api"] == "doxygen"
            else "stub page, Doxygen is not installed"
        ),
        "- [Architecture references](%s): SL-ARCH-001 to SL-ARCH-030 are Planned (ADR-0003)."
        % r("docs/arch/README.md"),
        "- [Operations references](%s): SL-OPS-001 to SL-OPS-010." % r("docs/ops/README.md"),
        "",
    ]


def page_overview(ctx):
    text = mdlib.read(os.path.join(ctx["root"], "README.md"))
    body = mdlib.rebase(text.rstrip("\n"), "", OUT_REL)
    return [GEN_NOTE, "[Back to the index](index.md)", "", body, ""]


def page_registry(ctx):
    r = ctx["rel"]
    docs = ctx["docs"]
    eps = ctx["episodes"]
    by_kind = collections.OrderedDict()
    for d in docs:
        by_kind.setdefault(d["kind"], collections.Counter())[d["status"]] += 1
    ep_status = collections.Counter(e["status"] for e in eps)
    out = [GEN_NOTE, "[Back to the index](index.md)", "", "# Registries", ""]
    out += [
        "The registries are authoritative (master plan 6.3 rule 1); the views below are generated and never "
        "hand-edited.",
        "",
        "## SL-REG-001: controlled documents",
        "",
        "Register: [registry/SL-REG-001-documents.json](%s). %d documents."
        % (r("registry/SL-REG-001-documents.json"), len(docs)),
        "",
    ]
    out += table(
        ["Kind", "Documents", "Statuses"],
        [(k, sum(c.values()), ", ".join("%s %d" % kv for kv in sorted(c.items()))) for k, c in by_kind.items()],
    )
    out += [
        "",
        "## SL-REG-002: episodes",
        "",
        "Register: [registry/SL-REG-002-episodes.json](%s). %d episodes: %s."
        % (
            r("registry/SL-REG-002-episodes.json"),
            len(eps),
            ", ".join("%s %d" % kv for kv in sorted(ep_status.items())),
        ),
        "",
        "## Generated views",
        "",
        "- [Views readme](%s)" % r("registry/views/README.md"),
        "- [Volumes](%s)" % r("registry/views/volumes.md"),
        "- [Volume graph (Mermaid)](%s)" % r("registry/views/volume-graph.mmd"),
        "- [Episodes (CSV)](%s)" % r("registry/views/episodes.csv"),
        "- [Kohi map](%s)" % r("registry/views/kohi-map.md"),
        "- [SL-REG-005 dependency view](%s)" % r("registry/views/SL-REG-005-dependencies.md"),
        "",
        "Registry readme: [registry/README.md](%s)." % r("registry/README.md"),
        "",
    ]
    return out


def page_adr(ctx):
    log = mdlib.read(os.path.join(ctx["root"], "docs", "gov", "SL-GOV-004-adr-log.md"))
    lines = [ln for _, ln in mdlib.lines_outside_fences(log)]
    start = next((i for i, ln in enumerate(lines) if ln.startswith("| ADR |")), None)
    if start is None:
        raise DocsBuildError("docs/gov/SL-GOV-004-adr-log.md: no ADR table")
    end = start
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    body = mdlib.rebase("\n".join(lines[start:end]), "docs/gov", OUT_REL)
    return [
        GEN_NOTE,
        "[Back to the index](index.md)",
        "",
        "# Architecture decisions",
        "",
        "From [SL-GOV-004](%s), generated from `docs/adr`. ADR index: [docs/adr/README.md](%s)."
        % (ctx["rel"]("docs/gov/SL-GOV-004-adr-log.md"), ctx["rel"]("docs/adr/README.md")),
        "",
        body,
        "",
    ]


def page_deps(ctx):
    lock = ctx["lock"]
    pol = lock.get("policy", {})
    rows = []
    for name in sorted(lock["packages"]):
        p = lock["packages"][name]
        prov = p.get("providers", {})
        version = p.get("version")
        if not version:
            sysp = prov.get("system", {})
            version = "%s..%s" % (sysp.get("min", "?"), sysp.get("tested", "?")) if sysp else "range"
        flags = []
        vend = prov.get("vendored")
        if vend and not vend.get("verified_upstream", True):
            flags.append("vendored copy not verified against upstream")
        rows.append(
            (
                name,
                version,
                p.get("license", "?"),
                p.get("role", ""),
                p.get("tier", ""),
                ", ".join(p.get("used_by", [])),
                ", ".join(prov),
                "; ".join(flags) or "none",
            )
        )
    out = [GEN_NOTE, "[Back to the index](index.md)", "", "# Dependencies and licences", ""]
    out += [
        "From `deps/deps.lock.json` (policy: [docs/gov/SL-GOV-008-dependency-policy.md](%s), ADR-0002: [ADR-0002](%s))."
        % (
            ctx["rel"]("docs/gov/SL-GOV-008-dependency-policy.md"),
            ctx["rel"]("docs/adr/ADR-0002-dependency-policy.md"),
        ),
        "Tier A is content-addressed; tier B is range-pinned. Network at configure: %s."
        % pol.get("network", "unknown"),
        "",
    ]
    out += table(["Package", "Version", "Licence", "Role", "Tier", "Used by", "Providers", "Open issue"], rows)
    allowed = pol.get("licenses_allowed", [])
    bad = sorted(set(r[2] for r in rows) - set(allowed))
    out += ["", "Allowed licences: %s." % (", ".join(allowed) or "none listed"), ""]
    out.append("Licences outside the allowed list: %s." % (", ".join(bad) if bad else "none"))
    out.append("")
    return out


def page_records(ctx):
    root, r = ctx["root"], ctx["rel"]
    out = [GEN_NOTE, "[Back to the index](index.md)", "", "# Controlled documents and records", ""]
    for title, sub in (
        ("Governance (SL-GOV)", "docs/gov"),
        ("Plans (SL-PLAN)", "docs/plan"),
        ("Volume specifications (SL-VOL)", "docs/vol"),
        ("Architecture decisions", "docs/adr"),
        ("Episode records", "docs/episodes"),
        ("Build", "docs/build"),
    ):
        out += ["## %s" % title, ""]
        names = sorted(n for n in os.listdir(os.path.join(root, sub)) if n.endswith(".md"))
        for n in names:
            heading = mdlib.first_heading(mdlib.read(os.path.join(root, sub, n)), n)
            out.append("- [%s](%s): %s" % (n, r("%s/%s" % (sub, n)), heading))
        out.append("")
    return out


def public_headers(root):
    found = []
    for base in HEADER_DIRS:
        for dp, dns, fns in os.walk(os.path.join(root, *base.split("/"))):
            dns.sort()
            for fn in sorted(fns):
                if fn.endswith((".h", ".hpp")):
                    found.append(os.path.relpath(os.path.join(dp, fn), root).replace(os.sep, "/"))
    return found


def page_api(ctx):
    out = [GEN_NOTE, "[Back to the index](index.md)", "", "# API reference", ""]
    if ctx["api"] == "doxygen":
        out += [
            "Doxygen HTML for `engine/core/include`, built with `docs/Doxyfile` (WARN_AS_ERROR): "
            "[api/html/index.html](%s)."
            % API_INDEX,
            "",
        ]
    else:
        out += [
            "Stub page: Doxygen is not installed, so no API reference was generated. Install it (`sudo pacman -Syu "
            "--needed doxygen`)",
            "and run `just docs` again to build the HTML reference from `docs/Doxyfile`.",
            "",
        ]
    out.append("Public headers (`engine/core/include`):")
    out.append("")
    for h in public_headers(ctx["root"]):
        out.append("- [%s](%s)" % (h, ctx["rel"](h)))
    out.append("")
    return out


PAGES = (
    ("index.md", page_index),
    ("overview.md", page_overview),
    ("registry.md", page_registry),
    ("adr.md", page_adr),
    ("dependencies.md", page_deps),
    ("records.md", page_records),
    ("api.md", page_api),
)


def build(root, out_dir, api):
    if api == "doxygen" and not os.path.isfile(os.path.join(out_dir, *API_INDEX.split("/"))):
        raise DocsBuildError("--api doxygen but %s/%s does not exist" % (OUT_REL, API_INDEX))
    ctx = {
        "root": root,
        "api": api,
        "rel": lambda target: rel_from_out(OUT_REL, target),
        "docs": load(root, "registry/SL-REG-001-documents.json")["documents"],
        "episodes": load(root, "registry/SL-REG-002-episodes.json")["episodes"],
        "lock": load(root, "deps/deps.lock.json"),
    }
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for name, fn in PAGES:
        with open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(fn(ctx)).rstrip("\n") + "\n")
        written.append(name)
    return written


def main(argv=None):
    ap = argparse.ArgumentParser(prog="build.py")
    ap.add_argument("--api", choices=("doxygen", "stub"), default="stub")
    ap.add_argument("--root", default=mdlib.repo_root())
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    out_dir = args.out or os.path.join(args.root, *OUT_REL.split("/"))
    try:
        written = build(args.root, out_dir, args.api)
    except (DocsBuildError, OSError, KeyError) as exc:
        print("docs: FAIL: %s" % exc)
        return 1
    print("docs: ok (%d pages in %s, api=%s)" % (len(written), OUT_REL, args.api))
    return 0


if __name__ == "__main__":
    sys.exit(main())
