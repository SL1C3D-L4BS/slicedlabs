"""registry-views: generate the human views of SL-REG-002 into registry/views/ (WO-011).

`python3 -I cmd_views.py [--root DIR] [--check]`

  (no flag)   write the four views
  --check     regenerate in memory and fail (exit 1, rule R-VIEW-DRIFT) when a committed view differs

Views (master plan section 6.3 rule 1: the registry is authoritative, views are never hand-edited):
  registry/views/volumes.md         table of the 42 volumes (part, episodes, title, depends_on_volumes)
  registry/views/volume-graph.mmd   Mermaid flowchart of depends_on_volumes (master plan section 4.2)
  registry/views/episodes.csv       id, volume, title, status, kohi_ref for every episode
  registry/views/kohi-map.md        Kohi arcs from the kohi_ref fields (master plan section 5.1)

`view_hashes(root)` returns {name: {expected_sha256, actual_sha256}}, the shape slib.rule_view_drift reads.
Output is deterministic: LF line endings, registry order, no timestamps. Stdlib only (ADR-0004).
"""

import csv
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import slgov  # noqa: E402
import slib  # noqa: E402

REGISTRY_REL = "registry/SL-REG-002-episodes.json"
VIEWS_REL = "registry/views"
VIEW_NAMES = ("volumes.md", "volume-graph.mmd", "episodes.csv", "kohi-map.md")
HEADER = (
    "generated by tools/governance/cmd_views.py from registry/SL-REG-002-episodes.json; "
    "do not edit, run `just registry-views`"
)
ARC_TABLE_HEADER = "| Kohi arc | Sliced Labs episodes | Count |"


def short_vol(vol_id):
    """SL-VOL-03 -> V03."""
    return "V" + vol_id.rsplit("-", 1)[1]


def md_cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def ranges(numbers):
    """[130, 131, 133, 147] -> '130-131, 133, 147' (3-digit, ASCII)."""
    out, i = [], 0
    nums = sorted(set(numbers))
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        if j == i:
            out.append("%03d" % nums[i])
        elif j == i + 1:
            out.append("%03d, %03d" % (nums[i], nums[j]))
        else:
            out.append("%03d-%03d" % (nums[i], nums[j]))
        i = j + 1
    return ", ".join(out)


def volumes_md(reg):
    lines = ["<!-- " + HEADER + " -->", "# Volumes (SL-REG-002)", ""]
    lines.append("| Volume | Part | Episodes | Title | Depends on volumes |")
    lines.append("| :---- | :---- | :---- | :---- | :---- |")
    for v in reg["volumes"]:
        deps = ", ".join(d.replace("SL-VOL-", "") for d in v["depends_on_volumes"]) or "none"
        lines.append(
            "| %s | %d | %03d-%03d | %s | %s |"
            % (v["id"].replace("SL-VOL-", ""), v["part"], v["first"], v["last"], md_cell(v["title"]), deps)
        )
    return "\n".join(lines) + "\n"


def volume_graph_mmd(reg):
    lines = ["%% " + HEADER, "flowchart LR"]
    for v in reg["volumes"]:
        label = ("%s %s" % (v["id"].replace("SL-VOL-", ""), v["title"])).replace('"', "#quot;")
        lines.append('  %s["%s"]' % (short_vol(v["id"]), label))
    for v in reg["volumes"]:
        for dep in v["depends_on_volumes"]:
            lines.append("  %s --> %s" % (short_vol(dep), short_vol(v["id"])))
    return "\n".join(lines) + "\n"


def episodes_csv(reg):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["id", "volume", "title", "status", "kohi_ref"])
    for e in reg["episodes"]:
        w.writerow([e["id"], e["volume"], e["title"], e["status"], e["kohi_ref"] or ""])
    return buf.getvalue()


def kohi_arcs(reg):
    """[(arc, [episode numbers])] in order of first appearance; kohi_ref 'a; b' lists two arcs."""
    order, found = [], {}
    for e in reg["episodes"]:
        if not e["kohi_ref"]:
            continue
        for arc in e["kohi_ref"].split("; "):
            if arc not in found:
                found[arc] = []
                order.append(arc)
            found[arc].append(e["number"])
    return [(arc, found[arc]) for arc in order]


def kohi_map_md(reg):
    lines = ["<!-- " + HEADER + " -->", "# Kohi alignment map (from kohi_ref)", ""]
    lines += [ARC_TABLE_HEADER, "| :---- | :---- | :---- |"]
    arcs = kohi_arcs(reg)
    for arc, nums in arcs:
        lines.append("| %s | %s | %d |" % (md_cell(arc), ranges(nums), len(nums)))
    lines += ["", "## Episodes (clean_room: true on every row)", ""]
    lines += ["| Episode | Kohi reference | clean_room |", "| :---- | :---- | :---- |"]
    for e in reg["episodes"]:
        if e["kohi_ref"]:
            lines.append("| %s | %s | true |" % (e["id"], md_cell(e["kohi_ref"])))
    return "\n".join(lines) + "\n"


GENERATORS = {
    "volumes.md": volumes_md,
    "volume-graph.mmd": volume_graph_mmd,
    "episodes.csv": episodes_csv,
    "kohi-map.md": kohi_map_md,
}


def generate(reg):
    """{view name: text} from a parsed registry."""
    return {name: GENERATORS[name](reg) for name in VIEW_NAMES}


def load_registry(root):
    return slib.load_json(os.path.join(root, *REGISTRY_REL.split("/")))


def read_view(root, name):
    path = os.path.join(root, *VIEWS_REL.split("/"), name)
    try:
        with open(path, encoding="utf-8", newline="") as fh:
            return fh.read()
    except (OSError, UnicodeDecodeError):
        return None


def view_hashes(root):
    """{name: {expected_sha256, actual_sha256}} for slib.rule_view_drift; a missing view hashes as ''."""
    want = generate(load_registry(root))
    out = {}
    for name in VIEW_NAMES:
        have = read_view(root, name)
        out[name] = {
            "expected_sha256": slib.sha256_text(want[name]),
            "actual_sha256": slib.sha256_text(have) if have is not None else "",
        }
    return out


def drift_errors(root):
    want = generate(load_registry(root))
    errors = []
    for name in VIEW_NAMES:
        label = "%s/%s" % (VIEWS_REL, name)
        have = read_view(root, name)
        if have is None:
            errors.append("%s:1: R-VIEW-DRIFT: view is missing; run `just registry-views`" % label)
        elif have != want[name]:
            errors.append(
                "%s:1: R-VIEW-DRIFT: view differs from the registry-generated content; run `just registry-views`"
                % label
            )
    return errors


def write_views(root):
    views = generate(load_registry(root))
    directory = os.path.join(root, *VIEWS_REL.split("/"))
    os.makedirs(directory, exist_ok=True)
    for name in VIEW_NAMES:
        with open(os.path.join(directory, name), "w", encoding="utf-8", newline="") as fh:
            fh.write(views[name])
    return VIEW_NAMES


def main(argv):
    root = slgov.ROOT
    args = list(argv[1:])
    check = False
    if "--check" in args:
        check = True
        args.remove("--check")
    if len(args) == 2 and args[0] == "--root":
        root = os.path.abspath(args[1])
    elif args:
        print("usage: cmd_views.py [--root DIR] [--check]", file=sys.stderr)
        return 2
    try:
        if check:
            return slgov.report("registry-views-check", drift_errors(root))
        names = write_views(root)
    except slib.LoadError as exc:
        print("registry-views: %s" % exc, file=sys.stderr)
        return 2
    print("registry-views: wrote %s" % ", ".join("%s/%s" % (VIEWS_REL, n) for n in names))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
