"""Generate docs/gov/SL-GOV-004-adr-log.md from docs/adr/ADR-*.md (a DOC.md document: the ADR log).

`python3 -I cmd_gen_adr_log.py [--root DIR]` writes the file; `--check` exits 1 when it is stale.
`adr-check` fails when the committed file differs from `render()`. The output is deterministic: no
timestamps, ADRs sorted by id. Stdlib only (ADR-0004).
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import slgov  # noqa: E402

LOG_REL = "docs/gov/SL-GOV-004-adr-log.md"
ADR_FILE_RE = re.compile(r"^(ADR-\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$")


def read_adrs(root):
    """Return [(id, filename, meta)] for every parseable ADR file, sorted by id."""
    adr_dir = os.path.join(root, "docs", "adr")
    found = []
    if not os.path.isdir(adr_dir):
        return found
    for name in sorted(os.listdir(adr_dir)):
        m = ADR_FILE_RE.match(name)
        if not m:
            continue
        try:
            with open(os.path.join(adr_dir, name), encoding="utf-8") as fh:
                meta = slgov.parse_front_matter(fh.read())
        except (OSError, UnicodeDecodeError, slgov.FrontMatterError):
            continue
        found.append((m.group(1), name, meta))
    return found


def _cell(value):
    if isinstance(value, list):
        value = ", ".join(value) if value else "none"
    return str(value or "none").replace("|", "/")


def render(root):
    adrs = read_adrs(root)
    ids = ", ".join(a[0] for a in adrs)
    rows = [
        "| ADR | Title | Status | Date | Supersedes | Decision refs |",
        "| :---- | :---- | :---- | :---- | :---- | :---- |",
    ]
    for adr_id, name, meta in adrs:
        rows.append(
            "| [%s](../adr/%s) | %s | %s | %s | %s | %s |"
            % (
                adr_id,
                name,
                _cell(meta.get("title")),
                _cell(meta.get("status")),
                _cell(meta.get("date")),
                _cell(meta.get("supersedes")),
                _cell(meta.get("decision_refs")),
            )
        )
    out = [
        "---",
        "# Generated by tools/governance/cmd_gen_adr_log.py from docs/adr. Do not edit by hand.",
        "id: SL-GOV-004",
        "kind: GOV",
        'title: "Architecture Decision Record log"',
        "status: Draft",
        "version: 0.1.0",
        "owner: founder",
        "episodes: []",
        "depends_on: []",
        "supersedes: []",
        "decisions: [%s]" % ids,
        "max_lines: 400",
        "---",
        "# SL-GOV-004: Architecture Decision Record log",
        "",
        "## Purpose",
        "",
        "SL-GOV-004 lists every architecture decision record of this repository (master plan, Required documents",
        "and registries). It is generated from `docs/adr/`; edit an ADR, then regenerate.",
        "",
        "## Status and decisions",
        "",
        *rows,
        "",
        "## Normative text",
        "",
        "- GOV4-R01: An ADR MUST be added when a change alters a locked decision (master plan section 6.3 rule 3).",
        "- GOV4-R02: This file MUST be regenerated, not hand-edited, and `adr-check` MUST fail when it is stale "
        "(ADR-0004).",
        "- GOV4-R03: An ADR id MUST NOT be reused or renumbered; a replacement supersedes the old ADR (master plan "
        "section 6.3 rule 2).",
        "",
        "## Measures and enforcement points",
        "",
        "- GOV4-R01 to GOV4-R03: `just adr-check` validates every ADR file and compares this file with the generator "
        "output.",
        "- Regenerate with `python3 -I tools/governance/cmd_gen_adr_log.py`.",
        "",
        "## Traceability",
        "",
        "Master plan section 6.3 (governance rules); episodes 001-020 (Volume 01); work order WO-003.",
        "",
        "## Open issues",
        "",
        "- Approval of this document is not recorded yet; the document register arrives with WO-005.",
        "",
        "## Change log",
        "",
        "| Version | Date | Change |",
        "| :---- | :---- | :---- |",
        "| 0.1.0 | generated | Generated from docs/adr. |",
        "",
    ]
    return "\n".join(out)


def main(argv):
    root = slgov.ROOT
    check = False
    args = argv[1:]
    if args[:1] == ["--root"] and len(args) >= 2:
        root = os.path.abspath(args[1])
        args = args[2:]
    if args == ["--check"]:
        check = True
    elif args:
        print("usage: cmd_gen_adr_log.py [--root DIR] [--check]", file=sys.stderr)
        return 2
    path = os.path.join(root, *LOG_REL.split("/"))
    text = render(root)
    if check:
        try:
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            print("gen-adr-log: FAIL: %s is stale; run python3 -I tools/governance/cmd_gen_adr_log.py" % LOG_REL)
            return 1
        print("gen-adr-log: ok")
        return 0
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("gen-adr-log: wrote %s (%d ADRs)" % (LOG_REL, len(read_adrs(root))))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
